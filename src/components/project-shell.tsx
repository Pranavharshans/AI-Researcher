import { sampleFiles } from "@/lib/sample-project";
import type { CompileState, DiagramPreviewApproval, DiagramPreviewStatus, ProjectFile } from "@/types/project";

export const ProjectShell = () => {
  const [projectFiles, setProjectFiles] = useState<ProjectFile[]>(sampleFiles);
  const [activeFileId, setActiveFileId] = useState(sampleFiles[0]?.id ?? "");
  const [compileState, setCompileState] = useState<CompileState>("idle");
  const [agentStatus, setAgentStatus] = useState("AI status: waiting for diagram request");
  const [isAddDiagramOpen, setIsAddDiagramOpen] = useState(false);
  const [diagramPreview, setDiagramPreview] = useState<DiagramPreviewApproval | null>(null);
  const [compiledDocument, setCompiledDocument] = useState<LatexCompileResponse | null>(null);
  const [lastDiagramInsertionUndo, setLastDiagramInsertionUndo] = useState<DiagramInsertionUndo | null>(null);
  const latestDiagramRequestId = useRef(0);
  const latestCursorRef = useRef<DiagramCursorSnapshot | null>(null);
  const latestMainCursorRef = useRef<DiagramCursorSnapshot | null>(null);

  const activeFile = useMemo(
    () => projectFiles.find((file) => file.id === activeFileId) ?? projectFiles[0],
    [activeFileId, projectFiles]
  );

  const runCompile = () => {
    void compileProjectFiles(projectFiles, activeFile.path);
  };

  const compileProjectFiles = async (files: ProjectFile[], activePath: string) => {
    const compilableFiles = sanitizeGeneratedFigureFiles(files);

    if (compilableFiles !== files) {
      setProjectFiles(compilableFiles);
    }

    setCompileState("running");
    setAgentStatus(`AI status: compiling ${activePath}`);

    try {
      const initialResult = await compileLatexProject(compilableFiles);
      const autoFix = initialResult.succeeded ? null : createPostCompileAutoFix(compilableFiles, initialResult);
      const result = autoFix ? await compileRepairedProjectFiles(autoFix) : initialResult;

      setCompiledDocument(result);
      setCompileState(result.succeeded ? "success" : "error");
      setAgentStatus(formatPostCompileAgentStatus(result, autoFix));
    } catch (error) {
      const message = error instanceof Error ? error.message : "LaTeX compile request failed.";

      setCompiledDocument({
        compileLog: message,
        errors: [],
        exitCode: null,
        pdfDataUrl: null,
        stderr: message,
        stdout: "",
        succeeded: false,
        timedOut: false
      });
      setCompileState("error");
      setAgentStatus(`AI status: ${message}`);
    }
  };

  const compileRepairedProjectFiles = async (autoFix: PostCompileAutoFix) => {
    setProjectFiles(autoFix.files);
    setAgentStatus(`AI status: ${autoFix.summary}; recompiling ${mainFilePath}`);

    return compileLatexProject(autoFix.files);
  };

  const updateFileContent = (fileId: string, content: string) => {
    setProjectFiles((files) => files.map((file) => (file.id === fileId ? { ...file, content } : file)));
  };

  const updateCursorSnapshot = (fileId: string, offset: number) => {
    latestCursorRef.current = { fileId, offset };

    if (projectFiles.find((file) => file.id === fileId)?.path === mainFilePath) {
      latestMainCursorRef.current = { fileId, offset };
    }
  };

  const startAddDiagram = () => {
    setAgentStatus("AI status: Add diagram selected; prompt dialog is next");
    setIsAddDiagramOpen(true);
  };

  const submitDiagramRequest = async (request: AddDiagramRequest) => {
    const requestId = latestDiagramRequestId.current + 1;

    latestDiagramRequestId.current = requestId;
    setCompileState("running");
    setAgentStatus("AI status: generating diagram with OpenRouter");
    setIsAddDiagramOpen(false);

    try {
      const generated = await generateDiagramSource(request);

      if (requestId !== latestDiagramRequestId.current) {
        return;
      }

      setCompileState("success");
      setAgentStatus(`AI status: diagram generated by ${generated.model}; waiting for approval`);
      const preview = createPreviewFromRequest(
        request,
        generated,
        getDiagramInsertionOffset(request, activeFile, latestCursorRef.current, latestMainCursorRef.current, projectFiles)
      );

      stageGeneratedDiagramSource(preview);
      setDiagramPreview(preview);
    } catch (error) {
      const message = error instanceof Error ? error.message : "Diagram generation failed.";

      if (requestId !== latestDiagramRequestId.current) {
        return;
      }

      setCompileState("success");
      setAgentStatus(`AI status: ${formatGenerationFailure(message)} Showing local fallback preview.`);
      const preview = createPreviewFromRequest(
        request,
        createFallbackGeneratedDiagram(message),
        getDiagramInsertionOffset(request, activeFile, latestCursorRef.current, latestMainCursorRef.current, projectFiles)
      );

      stageGeneratedDiagramSource(preview);
      setDiagramPreview(preview);
    }
  };

  const stageGeneratedDiagramSource = (preview: DiagramPreviewApproval) => {
    const generatedFileId = projectFiles.find((file) => file.path === preview.sourcePath)?.id ?? "generated-diagram-001";

    setProjectFiles((files) => saveGeneratedFigureSource(files, preview.sourcePath, preview.source));
    setActiveFileId(generatedFileId);
  };

  const updateDiagramApproval = (status: DiagramPreviewStatus) => {
    setDiagramPreview((preview) => (preview ? { ...preview, status } : preview));

    if (status === "kept") {
      setAgentStatus("AI status: diagram approved; insertion is next");
      return;
    }

    if (status === "changes-requested") {
      setAgentStatus("AI status: revision requested; feedback loop is next");
      return;
    }

    setAgentStatus("AI status: diagram discarded; source was not inserted");
  };

  const keepDiagram = () => {
    if (!diagramPreview) {
      return;
    }

    const insertion = insertApprovedDiagram(projectFiles, diagramPreview);
    setLastDiagramInsertionUndo({
      activeFileId,
      compiledDocument,
      files: projectFiles
    });
    setProjectFiles(insertion.files);
    setActiveFileId("main");
    setCompileState("running");
    setDiagramPreview(null);
    setAgentStatus(`AI status: diagram inserted into ${insertion.mainFilePath}; compiling main document`);
    void compileProjectFiles(insertion.files, insertion.mainFilePath);
  };

  const undoDiagramInsertion = () => {
    if (!lastDiagramInsertionUndo) {
      return;
    }

    setProjectFiles(lastDiagramInsertionUndo.files);
    setActiveFileId(lastDiagramInsertionUndo.activeFileId);
    setCompiledDocument(lastDiagramInsertionUndo.compiledDocument);
    setCompileState(lastDiagramInsertionUndo.compiledDocument ? (lastDiagramInsertionUndo.compiledDocument.succeeded ? "success" : "error") : "idle");
    setDiagramPreview(null);
    setLastDiagramInsertionUndo(null);
    setAgentStatus("AI status: diagram insertion undone");
  };

  const submitDiagramRevision = (feedback: string) => {
    setCompileState("running");
    setAgentStatus("AI status: revising existing diagram source");

    window.setTimeout(() => {
      setCompileState("success");
      setAgentStatus("AI status: revised diagram compiled; waiting for approval; OpenRouter pending key");
      setDiagramPreview((preview) => (preview ? revisePreviewFromFeedback(preview, feedback) : preview));
    }, 650);
  };

  return (
    <main className="project-shell" aria-label="Agentic LaTeX Diagram Editor">
      <header className="top-bar">
        <div className="project-identity">
          <button className="icon-button" type="button" aria-label="Toggle file tree">
            <PanelLeft aria-hidden="true" />
          </button>
          <div className="project-title-group">
            <div className="project-kicker">Research workspace</div>
            <button className="project-title-button" type="button">
              Learning Interpretable Transformers
              <ChevronDown aria-hidden="true" />
            </button>
          </div>
        </div>

        <div className="top-actions" aria-label="Project actions">
          <div className="search-box" role="search">
            <Search aria-hidden="true" />
            <span>Find in project</span>
            <kbd>/</kbd>
          </div>
          <button className="ghost-button" type="button">
            <GitBranch aria-hidden="true" />
            main
          </button>
          {lastDiagramInsertionUndo ? (
            <button className="ghost-button" type="button" onClick={undoDiagramInsertion}>
              <Undo2 aria-hidden="true" />
              Undo insert
            </button>
          ) : null}
          <button className="primary-button" type="button" onClick={runCompile}>
            <Play aria-hidden="true" />
            Compile
          </button>
          <button className="icon-button" type="button" aria-label="Project settings">
            <Settings aria-hidden="true" />
          </button>
        </div>
      </header>

      <section className="workspace-grid" aria-label="LaTeX editing workspace" data-preview-open={Boolean(diagramPreview)}>
        <aside className="file-sidebar" aria-label="Project files">
          <div className="panel-heading">
            <div>
              <p>Project</p>
              <h2>Files</h2>
            </div>
            <Folder aria-hidden="true" />
          </div>
          <FileTree files={projectFiles} activeFileId={activeFile.id} onSelectFile={setActiveFileId} />
        </aside>

        <EditorPane
          file={activeFile}
          onAddDiagram={startAddDiagram}
          onChangeFileContent={updateFileContent}
          onCursorChange={updateCursorSnapshot}
        />

        <PreviewPane
          compileState={compileState}
          compiledDocument={compiledDocument}
          diagramPreview={diagramPreview}
          onDiscardDiagram={() => updateDiagramApproval("discarded")}
          onKeepDiagram={keepDiagram}
          onRequestChanges={() => updateDiagramApproval("changes-requested")}
          onSubmitRevision={submitDiagramRevision}
        />
      </section>

      <StatusBar
        compileState={compileState}
        activeFilePath={activeFile?.path ?? "main.tex"}
        agentStatus={agentStatus}
        leftIcon={<FileCode2 aria-hidden="true" />}
        rightIcon={compileState === "success" ? <CheckCircle2 aria-hidden="true" /> : <TerminalSquare aria-hidden="true" />}
        agentIcon={<Bot aria-hidden="true" />}
      />
      <AddDiagramDialog
        isOpen={isAddDiagramOpen}
        onClose={() => setIsAddDiagramOpen(false)}
        onSubmit={submitDiagramRequest}
      />
    </main>
  );
};

