const mainFilePath = "main.tex";

const compileLatexProject = async (files: ProjectFile[]): Promise<LatexCompileResponse> => {
  const response = await fetch("/api/latex/compile", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      files,
      mainPath: mainFilePath
    })
  });
  const data = (await response.json()) as Partial<LatexCompileResponse> & { error?: string };

  if (!response.ok) {
    throw new Error(data.error ?? `LaTeX compile failed with status ${response.status}.`);
  }

  return {
    compileLog: data.compileLog ?? "",
    errorSummary: data.errorSummary,
    errors: data.errors ?? [],
    exitCode: data.exitCode ?? null,
    pdfDataUrl: data.pdfDataUrl ?? null,
    stderr: data.stderr ?? "",
    stdout: data.stdout ?? "",
    succeeded: Boolean(data.succeeded),
    timedOut: Boolean(data.timedOut)
  };
};

const formatPostCompileAgentStatus = (result: LatexCompileResponse, autoFix: PostCompileAutoFix | null) => {
  if (result.succeeded && autoFix) {
    return `AI status: ${autoFix.summary}; rendered ${mainFilePath}`;
  }

  if (result.succeeded) {
    return `AI status: rendered ${mainFilePath}`;
  }

  if (autoFix) {
    return `AI status: auto-fix attempted (${autoFix.summary}) but LaTeX compile still failed`;
  }

  return "AI status: LaTeX compile failed; inspect the preview log";
};

const createPostCompileAutoFix = (files: ProjectFile[], result: LatexCompileResponse): PostCompileAutoFix | null => {
  const undefinedColors = collectUndefinedXcolorColors(result);

  if (!undefinedColors.length) {
    return null;
  }

  const replacements = new Map<string, string>();
  let changed = false;
  const repairedFiles = files.map((file) => {
    if (!file.path.startsWith("figures/generated/")) {
      return file;
    }

    const repaired = repairGeneratedLatexColorAliases(file.content);

    repaired.replacements.forEach(([from, to]) => replacements.set(from, to));

    if (repaired.source === file.content) {
      return file;
    }

    changed = true;
    return { ...file, content: repaired.source };
  });

  if (!changed) {
    return null;
  }

  const replacementSummary = [...replacements.entries()].map(([from, to]) => `${from} -> ${to}`).join(", ");

  return {
    changedPaths: repairedFiles
      .filter((file, index) => file.content !== files[index]?.content)
      .map((file) => file.path),
    files: repairedFiles,
    summary: `auto-fixed generated xcolor names (${replacementSummary || undefinedColors.join(", ")})`
  };
};

const collectUndefinedXcolorColors = (result: LatexCompileResponse) => {
  const colors = new Set<string>();
  const errorText = result.errors.map((error) => error.rawMessage ?? "").join("\n");
  const text = `${errorText}\n${result.errorSummary ?? ""}\n${result.compileLog}`;
  const colorPattern = /Undefined color [`']([^`']+)[`']/g;
  let match = colorPattern.exec(text);

  while (match) {
    if (match[1]) {
      colors.add(match[1]);
    }

    match = colorPattern.exec(text);
  }

  return [...colors];
};

const generateDiagramSource = async (request: AddDiagramRequest): Promise<GeneratedDiagramSource> => {
  const response = await fetch("/api/diagram/generate", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify(request)
  });
  const data = (await response.json()) as Partial<GeneratedDiagramSource> & { detail?: string; error?: string };

  if (!response.ok) {
    throw new Error(data.detail ? `${data.error} ${data.detail}` : data.error ?? `OpenRouter request failed with status ${response.status}.`);
  }

  if (typeof data.tex !== "string" || typeof data.summary !== "string") {
    throw new Error("OpenRouter returned an unusable diagram response.");
  }

  return {
    tex: data.tex,
    summary: data.summary,
    provider: data.provider ?? "openrouter",
    model: data.model ?? "configured OpenRouter model",
    requiredPackages: data.requiredPackages ?? [],
    requiredTikzLibraries: data.requiredTikzLibraries ?? []
  };
};

const createPreviewFromRequest = (
  request: AddDiagramRequest,
  generated: GeneratedDiagramSource,
  insertionOffset: number | null
): DiagramPreviewApproval => ({
  id: "diagram-preview-001",
  prompt: request.prompt,
  outputTarget: request.outputTarget,
  insertionOffset,
  artifactPath: "artifacts/diagram_001.pdf",
  sourcePath: generatedFigurePath,
  accessibleSummary: generated.summary,
  repairSummary: `Standalone compile checkpoint prepared from ${generated.provider} model ${generated.model}.`,
  changes: [
    `Generated ${request.stylePreset} TikZ source from the captured prompt with ${generated.model}.`,
    formatGenerationRequirements(generated),
    "Compiled the standalone figure and prepared an approval checkpoint.",
    `Targeted output route: ${formatOutputTarget(request.outputTarget)}.`
  ],
  revisionHistory: [],
  source: sanitizeGeneratedTikzSource(generated.tex),
  status: "ready"
});

const createFallbackGeneratedDiagram = (reason: string): GeneratedDiagramSource => ({
  model: "local fallback",
  provider: "OpenRouter unavailable",
  requiredPackages: ["tikz"],
  requiredTikzLibraries: [],
  summary:
    `Local fallback preview because ${formatGenerationFailure(reason).toLowerCase()}`,
  tex: String.raw`\begin{tikzpicture}[node distance=1.9cm, >=stealth]
  \node[draw, rounded corners, fill=green!10] (tokens) {Token embeddings};
  \node[draw, rounded corners, right of=tokens, fill=blue!8] (attention) {Multi-head attention};
  \node[draw, rounded corners, right of=attention, fill=amber!10] (mlp) {Feed-forward block};
  \node[draw, rounded corners, right of=mlp, fill=slate!8] (logits) {Logits};
  \draw[->] (tokens) -- (attention);
  \draw[->] (attention) -- (mlp);
  \draw[->] (mlp) -- (logits);
\end{tikzpicture}
% Fallback reason: ${reason}`
});

const formatGenerationFailure = (reason: string) => {
  if (/429|rate limit/i.test(reason)) {
    return "OpenRouter rate-limited the configured model/key.";
  }

  return reason;
};

const formatGenerationRequirements = (generated: GeneratedDiagramSource) => {
  const packages = generated.requiredPackages.length ? generated.requiredPackages.join(", ") : "none";
  const libraries = generated.requiredTikzLibraries.length ? generated.requiredTikzLibraries.join(", ") : "none";

  return `Required packages: ${packages}; TikZ libraries: ${libraries}.`;
};

const getDiagramInsertionOffset = (
  request: AddDiagramRequest,
  activeFile: ProjectFile,
  cursorSnapshot: DiagramCursorSnapshot | null,
  mainCursorSnapshot: DiagramCursorSnapshot | null,
  files: ProjectFile[]
) => {
  if (request.outputTarget !== "inline") {
    return null;
  }

  if (activeFile.path === mainFilePath && cursorSnapshot?.fileId === activeFile.id) {
    return Math.min(Math.max(cursorSnapshot.offset, 0), activeFile.content.length);
  }

  const mainFile = files.find((file) => file.path === mainFilePath);

  if (!mainFile || mainCursorSnapshot?.fileId !== mainFile.id) {
    return null;
  }

  return Math.min(Math.max(mainCursorSnapshot.offset, 0), mainFile.content.length);
};

type DiagramInsertionResult = {
  files: ProjectFile[];
  mainFilePath: string;
};

const generatedFigurePath = "figures/generated/diagram_001.tex";
const diagramInsertionMarker = "% Right-click in the editor to add a generated diagram here.";
const naturalLanguageDiagramRequestMarker = "% NATURAL LANGUAGE DIAGRAM REQUEST";

const insertApprovedDiagram = (files: ProjectFile[], preview: DiagramPreviewApproval): DiagramInsertionResult => {
  const savedFigureFiles = saveGeneratedFigureSource(files, preview.sourcePath, preview.source);
  const filesWithMainInsertion = savedFigureFiles.map((file) => {
    if (file.path !== "main.tex") {
      return file;
    }

    return {
      ...file,
      content: insertDiagramInputIntoMain(file.content, preview)
    };
  });

  return {
    files: filesWithMainInsertion,
    mainFilePath: "main.tex"
  };
};

const saveGeneratedFigureSource = (files: ProjectFile[], sourcePath: string, source: string) => {
  const normalizedSourcePath = sourcePath.startsWith("figures/generated/") ? sourcePath : generatedFigurePath;
  const savedSource = `${sanitizeGeneratedTikzSource(source).trim()}\n`;
  const hasFigureFile = files.some((file) => file.path === normalizedSourcePath);

  if (hasFigureFile) {
    return files.map((file) => (file.path === normalizedSourcePath ? { ...file, content: savedSource } : file));
  }

  return [
    ...files,
    {
      id: "generated-diagram-001",
      path: normalizedSourcePath,
      language: "latex" as const,
      content: savedSource
    }
  ];
};

const sanitizeGeneratedFigureFiles = (files: ProjectFile[]) => {
  let changed = false;
  const sanitizedFiles = files.map((file) => {
    if (!file.path.startsWith("figures/generated/")) {
      return file;
    }

    const sanitizedContent = sanitizeGeneratedTikzSource(file.content);

    if (sanitizedContent === file.content) {
      return file;
    }

    changed = true;
    return { ...file, content: sanitizedContent };
  });

  return changed ? sanitizedFiles : files;
};

const insertDiagramInputIntoMain = (mainSource: string, preview: DiagramPreviewApproval) => {
  if (preview.outputTarget === "inline" && preview.insertionOffset !== null) {
    return ensureDiagramLatexDependencies(insertInlineDiagramAtOffset(mainSource, preview));
  }

  const sourceWithRequiredPackages = ensureDiagramLatexDependencies(mainSource);
  const figureBlock = createFigureInsertionBlock(preview);
  const placeholderReplacement = replaceNaturalLanguageDiagramPlaceholder(sourceWithRequiredPackages, preview);

  if (placeholderReplacement !== sourceWithRequiredPackages) {
    return placeholderReplacement;
  }

  if (sourceWithRequiredPackages.includes("\\label{fig:generated-diagram-001}")) {
    return sourceWithRequiredPackages.replace(
      /\\begin\{figure\}\[ht\][\s\S]*?\\label\{fig:generated-diagram-001\}\n\\end\{figure\}/,
      figureBlock
    );
  }

  if (sourceWithRequiredPackages.includes(diagramInsertionMarker)) {
    return sourceWithRequiredPackages.replace(diagramInsertionMarker, `${diagramInsertionMarker}\n\n${figureBlock}`);
  }

  return sourceWithRequiredPackages.replace("\\end{document}", `${figureBlock}\n\n\\end{document}`);
};

const insertInlineDiagramAtOffset = (mainSource: string, preview: DiagramPreviewApproval) => {
  const boundedOffset = Math.min(Math.max(preview.insertionOffset ?? mainSource.length, 0), mainSource.length);
  const figureBlock = createFigureInsertionBlock(preview);
  const prefix = mainSource.slice(0, boundedOffset).replace(/[ \t]*$/, "");
  const suffix = mainSource.slice(boundedOffset).replace(/^[ \t]*/, "");

  return `${prefix}\n\n${figureBlock}\n\n${suffix}`;
};

const ensureDiagramLatexDependencies = (source: string) => {
  const withGraphicx = ensureUsePackage(source, "graphicx");
  const withTikz = ensureUsePackage(withGraphicx, "tikz");

  return ensureTikzLibraries(withTikz, ["arrows.meta", "positioning", "shapes.geometric", "fit", "calc"]);
};

const ensureUsePackage = (source: string, packageName: string) => {
  const packagePattern = new RegExp(`\\\\usepackage(?:\\[[^\\]]*\\])?\\{[^}]*\\b${packageName}\\b[^}]*\\}`);

  if (packagePattern.test(source)) {
    return source;
  }

  const lastUsePackageMatch = [...source.matchAll(/\\usepackage(?:\[[^\]]*\])?\{[^}]+\}/g)].at(-1);

  if (lastUsePackageMatch?.index !== undefined) {
    const insertAt = lastUsePackageMatch.index + lastUsePackageMatch[0].length;

    return `${source.slice(0, insertAt)}\n\\usepackage{${packageName}}${source.slice(insertAt)}`;
  }

  return source.replace(/(\\documentclass(?:\[[^\]]*\])?\{[^}]+\})/, `$1\n\\usepackage{${packageName}}`);
};

const ensureTikzLibraries = (source: string, libraries: string[]) => {
  const existingMatch = source.match(/\\usetikzlibrary\{([^}]*)\}/);

  if (existingMatch?.[1]) {
    const mergedLibraries = mergeCommaList(existingMatch[1], libraries);

    return source.replace(existingMatch[0], `\\usetikzlibrary{${mergedLibraries.join(",")}}`);
  }

  const tikzPackageMatch = source.match(/\\usepackage(?:\[[^\]]*\])?\{[^}]*\btikz\b[^}]*\}/);

  if (tikzPackageMatch?.index !== undefined) {
    const insertAt = tikzPackageMatch.index + tikzPackageMatch[0].length;

    return `${source.slice(0, insertAt)}\n\\usetikzlibrary{${libraries.join(",")}}${source.slice(insertAt)}`;
  }

  return source;
};

const mergeCommaList = (existing: string, required: string[]) => {
  const values = existing
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);

  return [...new Set([...values, ...required])];
};

const latexColorAliases: Record<string, string> = {
  amber: "orange",
  emerald: "green",
  fuchsia: "magenta",
  grey: "gray",
  indigo: "blue",
  neutral: "gray",
  rose: "red",
  sky: "cyan",
  slate: "gray",
  stone: "gray",
  teal: "cyan",
  violet: "purple",
  zinc: "gray"
};

const repairGeneratedLatexColorAliases = (source: string) => {
  const replacements = new Map<string, string>();
  const repairedSource = source.replace(/\[([^\]]*)\]/g, (match, rawOptions: string) => {
    const tokens = splitTikzOptions(rawOptions);
    let changed = false;
    const repairedTokens = tokens.map((token) => {
      const repaired = repairTikzColorOptionToken(token);

      if (repaired.token !== token) {
        changed = true;
        replacements.set(repaired.from, repaired.to);
      }

      return repaired.token;
    });

    return changed ? `[${repairedTokens.join(", ")}]` : match;
  });

  return {
    replacements: [...replacements.entries()],
    source: repairedSource
  };
};

const repairTikzColorOptionToken = (token: string) => {
  const colorOptionMatch = token.match(/^(fill|draw|text|color)=([A-Za-z]+)((?:![A-Za-z0-9.]+)*)$/);

  if (!colorOptionMatch?.[1] || !colorOptionMatch[2]) {
    return { token, from: "", to: "" };
  }

  const from = colorOptionMatch[2];
  const to = latexColorAliases[from.toLowerCase()];

  if (!to) {
    return { token, from: "", to: "" };
  }

  return {
    token: `${colorOptionMatch[1]}=${to}${colorOptionMatch[3] ?? ""}`,
    from,
    to
  };
};

const sanitizeGeneratedTikzSource = (source: string) =>
  source.replace(/\[([^\]]*)\]/g, (match, rawOptions: string) => {
    const sanitizedOptions = sanitizeTikzOptionList(rawOptions);

    return sanitizedOptions === rawOptions ? match : `[${sanitizedOptions}]`;
  });

const sanitizeTikzOptionList = (rawOptions: string) => {
  const tokens = splitTikzOptions(rawOptions);

  return tokens.map(sanitizeTikzOptionToken).join(", ");
};

const splitTikzOptions = (rawOptions: string) => {
  const tokens: string[] = [];
  let current = "";
  let braceDepth = 0;
  let parenDepth = 0;

  for (const character of rawOptions) {
    if (character === "{" && parenDepth === 0) {
      braceDepth += 1;
    } else if (character === "}" && braceDepth > 0 && parenDepth === 0) {
      braceDepth -= 1;
    } else if (character === "(" && braceDepth === 0) {
      parenDepth += 1;
    } else if (character === ")" && parenDepth > 0 && braceDepth === 0) {
      parenDepth -= 1;
    }

    if (character === "," && braceDepth === 0 && parenDepth === 0) {
      tokens.push(current.trim());
      current = "";
    } else {
      current += character;
    }
  }

  if (current.trim()) {
    tokens.push(current.trim());
  }

  return tokens;
};

const sanitizeTikzOptionToken = (token: string) => {
  if (token === "italic") {
    return "font=\\itshape";
  }

  if (token === "bold") {
    return "font=\\bfseries";
  }

  if (token === "small") {
    return "font=\\small";
  }

  if (token === "large") {
    return "font=\\large";
  }

  return token;
};

const replaceNaturalLanguageDiagramPlaceholder = (source: string, preview: DiagramPreviewApproval) => {
  if (!source.includes(naturalLanguageDiagramRequestMarker)) {
    return source;
  }

  const inputBlock = createResponsiveFigureInput(preview);
  const placeholderPattern =
    /\n?% NATURAL LANGUAGE DIAGRAM REQUEST[\s\S]*?\\fbox\{\s*\\begin\{minipage\}\{[^}]+\}[\s\S]*?\\end\{minipage\}\s*\}/;

  if (!placeholderPattern.test(source)) {
    return source;
  }

  return source.replace(placeholderPattern, `\n${inputBlock}`);
};

const createFigureInsertionBlock = (preview: DiagramPreviewApproval) => {
  const inputBlock = createResponsiveFigureInput(preview);

  return String.raw`\begin{figure}[ht]
  \centering
  ${inputBlock}
  \caption{Generated diagram.}
  \label{fig:generated-diagram-001}
\end{figure}`;
};

const createResponsiveFigureInput = (preview: DiagramPreviewApproval) => {
  const inputPath = (preview.sourcePath.startsWith("figures/generated/") ? preview.sourcePath : generatedFigurePath).replace(/\.tex$/, "");

  return String.raw`\resizebox{\linewidth}{!}{%
  \input{${inputPath}}
}`;
};

const formatOutputTarget = (target: AddDiagramRequest["outputTarget"]) => {
  if (target === "figure-file") {
    return "generated figure file";
  }

  if (target === "replace-placeholder") {
    return "selected placeholder";
  }

  return "current cursor position";
};

const revisePreviewFromFeedback = (preview: DiagramPreviewApproval, feedback: string): DiagramPreviewApproval => {
  const revisionNumber = preview.revisionHistory.length + 1;
  const revisedSource = applyLocalRevisionToSource(preview.source, feedback, revisionNumber);

  return {
    ...preview,
    source: revisedSource,
    accessibleSummary: `${preview.accessibleSummary} Revision ${revisionNumber} applies: ${feedback}.`,
    repairSummary: "Revision compiled from the existing diagram source and returned to approval. OpenRouter remains pending key.",
    changes: [
      `Revision ${revisionNumber}: ${feedback}`,
      "Used the existing TikZ source as the starting point.",
      "Recompiled the revised standalone figure and returned to preview approval."
    ],
    revisionHistory: [...preview.revisionHistory, feedback],
    status: "ready"
  };
};

const applyLocalRevisionToSource = (source: string, feedback: string, revisionNumber: number) => {
  const escapedFeedback = feedback.replaceAll("\n", " ").trim();
  const annotatedSource = source.includes("% User revision")
    ? source.replace(/% User revision \d+: .*\n/, `% User revision ${revisionNumber}: ${escapedFeedback}\n`)
    : source.replace("\\begin{tikzpicture}", `% User revision ${revisionNumber}: ${escapedFeedback}\n\\begin{tikzpicture}`);

  if (/curv|bend|arc/i.test(feedback)) {
    return annotatedSource.replaceAll("\\draw[->]", "\\draw[->, bend left=12]");
  }

  if (/label|annotation|caption/i.test(feedback)) {
    return annotatedSource.replace(
      "\\node[draw, rounded corners, right of=attention, fill=amber!10] (mlp) {Feed-forward block};",
      "\\node[draw, rounded corners, right of=attention, fill=amber!10] (mlp) {Feed-forward block\\\\small revised};"
    );
  }

  return annotatedSource;
};
